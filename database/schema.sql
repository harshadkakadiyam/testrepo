-- MySQL schema for Gujarati Billing App
CREATE TABLE IF NOT EXISTS products (
  id VARCHAR(32) PRIMARY KEY,
  name VARCHAR(255) NOT NULL,
  price DECIMAL(12,2) NOT NULL DEFAULT 0.00,
  majuri DECIMAL(12,2) NOT NULL DEFAULT 0.00,
  hsn_code VARCHAR(32) NULL,
  gst_percentage DECIMAL(5,2) NOT NULL DEFAULT 0.00,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS customers (
  id INT AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(255) NOT NULL,
  phone VARCHAR(32) NULL,
  address TEXT NULL,
  gstin VARCHAR(32) NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS chalans (
  id INT AUTO_INCREMENT PRIMARY KEY,
  chalan_no VARCHAR(50) NOT NULL UNIQUE,
  chalan_date DATE NOT NULL,
  customer_id INT NOT NULL,
  total_amount DECIMAL(12,2) NOT NULL DEFAULT 0.00,
  total_gst DECIMAL(12,2) NOT NULL DEFAULT 0.00,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_chalans_customer FOREIGN KEY (customer_id) REFERENCES customers(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS chalan_items (
  id INT AUTO_INCREMENT PRIMARY KEY,
  chalan_id INT NOT NULL,
  product_id VARCHAR(32) NOT NULL,
  product_name VARCHAR(255) NOT NULL,
  qty DECIMAL(12,3) NOT NULL DEFAULT 0,
  price DECIMAL(12,2) NOT NULL DEFAULT 0.00,
  majuri DECIMAL(12,2) NOT NULL DEFAULT 0.00,
  gst_percentage DECIMAL(5,2) NOT NULL DEFAULT 0.00,
  line_total DECIMAL(12,2) NOT NULL DEFAULT 0.00,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_chalan_items_chalan FOREIGN KEY (chalan_id) REFERENCES chalans(id) ON DELETE CASCADE,
  CONSTRAINT fk_chalan_items_product FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS invoices (
  id INT AUTO_INCREMENT PRIMARY KEY,
  invoice_no VARCHAR(50) NOT NULL UNIQUE,
  invoice_date DATE NOT NULL,
  chalan_id INT NOT NULL,
  taxable_value DECIMAL(12,2) NOT NULL DEFAULT 0.00,
  cgst DECIMAL(12,2) NOT NULL DEFAULT 0.00,
  sgst DECIMAL(12,2) NOT NULL DEFAULT 0.00,
  igst DECIMAL(12,2) NOT NULL DEFAULT 0.00,
  total_amount DECIMAL(12,2) NOT NULL DEFAULT 0.00,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_invoices_chalan FOREIGN KEY (chalan_id) REFERENCES chalans(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- Sequences simple table for unique numbers
CREATE TABLE IF NOT EXISTS sequences (
  seq_name VARCHAR(64) PRIMARY KEY,
  current_value INT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

INSERT INTO sequences (seq_name, current_value) VALUES
  ('chalan_no', 0) ON DUPLICATE KEY UPDATE current_value=current_value,
  ('invoice_no', 0) ON DUPLICATE KEY UPDATE current_value=current_value;
